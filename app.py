def ejecutar_pca(deptos, anio_min, anio_max, n_comp=5):
    try:
        d = preparar(DF_PANEL, deptos, anio_min, anio_max)
        X = d[INDICADORES].dropna()
        if len(X) < 25: return "Datos insuficientes.", None, None
        Xs = StandardScaler().fit_transform(X)
        n_comp = min(int(n_comp), Xs.shape[1], Xs.shape[0]-1)
        pca = PCA(n_components=n_comp).fit(Xs)
        var = pca.explained_variance_ratio_
        fig_scree = go.Figure()
        fig_scree.add_trace(go.Bar(x=[f"PC{i+1}" for i in range(n_comp)], y=var))
        fig_scree.add_trace(go.Scatter(x=[f"PC{i+1}" for i in range(n_comp)], y=np.cumsum(var), mode="lines+markers"))
        fig_scree.update_layout(title="Scree Plot")
        loadings = pd.DataFrame(pca.components_.T, columns=[f"PC{i+1}" for i in range(n_comp)], index=INDICADORES)
        fig_load = px.imshow(loadings.round(2), text_auto=False, aspect="auto", color_continuous_scale="RdBu_r",
                             title="Cargas factoriales")
        return f"Varianza: {np.round(var,3).tolist()}\nAcumulada: {np.round(np.cumsum(var),3).tolist()}", fig_scree, fig_load
    except Exception as e:
        return f"Error: {e}", None, None

def estimar_var(deptos, vars_sel, anio_min, anio_max, maxlags=2):
    try:
        d = preparar(DF_PANEL, deptos, anio_min, anio_max)
        if not vars_sel or len(vars_sel) < 2:
            vars_sel = ["PIB", "Tasa_Desempleo", "Homicidios", "IPM"]
        if deptos and len(deptos) == 1 and "Todos" not in deptos:
            ts = d[d["departamento"] == deptos[0]].set_index("anio")[vars_sel].sort_index()
        else:
            ts = d.groupby("anio")[vars_sel].mean().sort_index()
        ts = ts.dropna()
        if len(ts) < 12: return "Series muy cortas.", None
        model = VAR(ts)
        order = model.select_order(maxlags=min(int(maxlags), len(ts)//3))
        res = model.fit(order.aic)
        granger = []
        for v in ts.columns:
            try:
                g = res.test_causality(v, [c for c in ts.columns if c != v], kind="f")
                granger.append(f"- {v}: p={g.pvalue:.4f}")
            except: pass
        irf = res.irf(8)
        fig = go.Figure()
        if ts.shape[1] >= 2:
            fig.add_trace(go.Scatter(y=irf.irfs[:,0,1], mode="lines+markers", name=f"{ts.columns[0]} ← {ts.columns[1]}"))
        fig.update_layout(title="IRF")
        return f"Lag AIC: {order.aic}\n\nGranger:\n" + "\n".join(granger) + "\n\n" + str(res.summary())[:2200], fig
    except Exception as e:
        return f"Error: {e}", None

