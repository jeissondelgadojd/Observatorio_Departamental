def test_moran(indicador, anio, k=5):
    if not SPATIAL_AVAILABLE:
        return "libpysal/esda no disponibles."
    try:
        d = DF_PANEL[DF_PANEL["anio"]==int(anio)].dropna(subset=[indicador]).sort_values("departamento").reset_index(drop=True)
        if len(d) < 8: return "Pocas observaciones."
        w = KNN.from_dataframe(d.assign(x=range(len(d)), y=0), k=min(int(k), len(d)-1))
        w.transform = "r"
        mi = Moran(d[indicador].values, w)
        interp = "Autocorrelación positiva significativa" if (mi.p_sim < 0.05 and mi.I > 0) else "No significativa"
        return f"**I de Moran – {indicador} ({anio})**\nI = {mi.I:.4f} | p-sim = {mi.p_sim:.4f}\n→ {interp}"
    except Exception as e:
        return f"Error: {e}"

def entrenar_ml(target, features, anio_min, anio_max, modelo):
    try:
        d = preparar(DF_PANEL, anio_min=anio_min, anio_max=anio_max).dropna()
        feats = [f for f in features if f in d.columns and f != target]
        if not feats: return "Seleccione features.", None, None
        X, y = d[feats], d[target]
        Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.25, random_state=42)
        if modelo == "Ridge":
            pipe = Pipeline([("sc", StandardScaler()), ("m", RidgeCV(alphas=np.logspace(-3,3,40)))])
        elif modelo == "LASSO":
            pipe = Pipeline([("sc", StandardScaler()), ("m", LassoCV(cv=5))])
        elif modelo == "SVR":
            pipe = Pipeline([("sc", StandardScaler()), ("m", SVR(C=10))])
        else:
            pipe = Pipeline([("sc", StandardScaler()), ("m", MLPRegressor(hidden_layer_sizes=(64,32), max_iter=400, random_state=42))])
        pipe.fit(Xtr, ytr)
        pred = pipe.predict(Xte)
        rmse = np.sqrt(mean_squared_error(yte, pred))
        r2 = r2_score(yte, pred)
        fig_pred = go.Figure()
        fig_pred.add_trace(go.Scatter(x=yte, y=pred, mode="markers", opacity=0.6))
        lims = [min(yte.min(), pred.min()), max(yte.max(), pred.max())]
        fig_pred.add_trace(go.Scatter(x=lims, y=lims, mode="lines", line=dict(dash="dash")))
        fig_pred.update_layout(title=f"{modelo}: Predicho vs Real")
        fig_imp = None
        if modelo in ["Ridge", "LASSO"]:
            coef = pipe.named_steps["m"].coef_
            imp = pd.DataFrame({"feature": feats, "coef": coef}).sort_values("coef", key=abs, ascending=False)
            fig_imp = px.bar(imp, x="coef", y="feature", orientation="h", title=f"Coeficientes {modelo}",
                             color="coef", color_continuous_scale="RdBu_r")
        return f"**{modelo}** | {target}\nRMSE={rmse:.3f} | R²={r2:.3f}", fig_pred, fig_imp
    except Exception as e:
        return f"Error: {e}", None, None

def simulador(target, features, vals):
    try:
        d = preparar(DF_PANEL).dropna()
        feats = [f for f in features if f in d.columns and f != target]
        X, y = d[feats], d[target]
        pipe = Pipeline([("sc", StandardScaler()), ("m", Ridge(alpha=1.0))])
        pipe.fit(X, y)
        base = X.mean().values.reshape(1, -1)
        pred_base = pipe.predict(base)[0]
        esc = base.copy()
        for i, f in enumerate(feats):
            if f in vals and vals[f] is not None:
                esc[0, i] = float(vals[f])
        pred_cf = pipe.predict(esc)[0]
        txt = f"**{target}**\nBase: **{pred_base:.2f}**\nEscenario: **{pred_cf:.2f}**\nΔ = {pred_cf-pred_base:+.2f}"
        fig = go.Figure(go.Indicator(mode="number+delta", value=pred_cf, delta={"reference": pred_base}, title={"text": target}))
        fig.update_layout(height=240)
        return txt, fig
    except Exception as e:
        return f"Error: {e}", None

def explicar_shap(target, features):
    if not SHAP_AVAILABLE: return "Instale shap.", None
    try:
        d = preparar(DF_PANEL).dropna()
        feats = [f for f in features if f in d.columns and f != target][:8]
        X = StandardScaler().fit_transform(d[feats])
        model = Ridge(alpha=1.0).fit(X, d[target])
        explainer = shap.LinearExplainer(model, X)
        sv = explainer.shap_values(X)
        mean_abs = np.abs(sv).mean(0)
        imp = pd.DataFrame({"feature": feats, "mean_|SHAP|": mean_abs}).sort_values("mean_|SHAP|")
        fig = px.bar(imp, x="mean_|SHAP|", y="feature", orientation="h", title=f"SHAP – {target}",
                     color="mean_|SHAP|", color_continuous_scale="Viridis")
        return "Importancia media |SHAP|", fig
    except Exception as e:
        return f"Error: {e}", None

